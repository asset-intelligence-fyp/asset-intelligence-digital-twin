#!/usr/bin/env python3
"""Quantitative sanity checks on synthetic climate, occupancy, humidity and CO₂.

These tests establish internal consistency, NOT external realism or model accuracy.
"""
import argparse,csv,json,collections,math,statistics
from datetime import date
from pathlib import Path

def corr(pairs):
 n,sx,sy,sxx,syy,sxy=0,0,0,0,0,0
 for x,y in pairs:
  n+=1;sx+=x;sy+=y;sxx+=x*x;syy+=y*y;sxy+=x*y
 den=(n*sxx-sx*sx)*(n*syy-sy*sy)
 return (n*sxy-sx*sy)/math.sqrt(den) if den>0 else float('nan')

def run(root,out):
 root=Path(root);results={'years':{},'statistical_relationships':{},'notes':[]}
 pooled=collections.defaultdict(list); cpairs=[];holiday_counts=[]
 for y in range(2019,2026):
  p=root/str(y);meta=json.loads((p/'run_manifest.json').read_text())
  assert meta['sensor_count']==19
  assert meta['expected_sensor_readings']==meta['rows']['sensor_history']
  assert meta['timestamps']==(date(y+1,1,1)-date(y,1,1)).days*288
  work=collections.Counter()
  with (p/'calendar.csv').open(newline='',encoding='utf8') as f:
   for r in csv.DictReader(f):work['holidays']+=int(r['is_holiday']);work['workdays']+=int(r['is_workday'])
  expected=['L03-OPEN-01','L03-MEET-01']
  with (p/'training_features.csv').open(newline='',encoding='utf8') as f:
   for row in csv.DictReader(f):
    if int(row['timestamp'][11:13]) not in (10,11,12,13,14,15,16):continue
    if row['humidity_pct']=='' or row['co2_ppm']=='' or row['local_rain_mm_h']=='':continue
    hh=float(row['humidity_pct']); co2=float(row['co2_ppm']);n=int(row['headcount']);rain=int(row['rain_wet']);ac=int(row['ac_on']);
    region='open' if row['room_id']==expected[0] else 'meeting'
    pooled[f'{region}_rain_{rain}_ac_{ac}_RH'].append(hh)
    pooled[f'{region}_occupied_{int(n>0)}_CO2'].append(co2)
    if region=='meeting':cpairs.append((n,co2))
  with (p/'weather_5min.csv').open(newline='',encoding='utf8') as f:
   for r in csv.DictReader(f):
    if r['local_rain_mm_h']!='':
     if r['timestamp'][5:7]=='01':pooled['jan_rain'].append(float(r['local_rain_mm_h']))
     if r['timestamp'][5:7]=='07':pooled['jul_rain'].append(float(r['local_rain_mm_h']))
  results['years'][str(y)]={'sensor_rows':meta['rows']['sensor_history'],'time_points':meta['timestamps'],'holidays':work['holidays'],'office_workdays':work['workdays'],'weather_source':meta['weather_provenance']}
  print('QC processed',y,flush=True)
 def avg(key):return statistics.fmean(pooled[key]) if pooled[key] else None
 z={
 'open_RH_rain_ac_off':round(avg('open_rain_1_ac_0_RH') or 0,2),
 'open_RH_dry_ac_off':round(avg('open_rain_0_ac_0_RH') or 0,2),
 'open_RH_rain_ac_on':round(avg('open_rain_1_ac_1_RH') or 0,2),
 'open_RH_dry_ac_on':round(avg('open_rain_0_ac_1_RH') or 0,2),
 'meeting_CO2_occupied':round(avg('meeting_occupied_1_CO2') or 0,1),
 'meeting_CO2_empty':round(avg('meeting_occupied_0_CO2') or 0,1),
 'meeting_headcount_CO2_correlation':round(corr(cpairs),3),
 'average_january_local_rain_rate_mm_h':round(avg('jan_rain') or 0,3),
 'average_july_local_rain_rate_mm_h':round(avg('jul_rain') or 0,3)}
 results['statistical_relationships']=z
 results['checks']={
  'rain_associated_with_higher_open_RH_ac_off':z['open_RH_rain_ac_off']>z['open_RH_dry_ac_off'],
  'rain_associated_with_higher_open_RH_ac_on':z['open_RH_rain_ac_on']>z['open_RH_dry_ac_on'],
  'occupied_meeting_higher_CO2':z['meeting_CO2_occupied']>z['meeting_CO2_empty']+50,
  'positive_meeting_headcount_CO2_corr':z['meeting_headcount_CO2_correlation']>.25,
  'wet_season_jan_higher_rain_than_jul':z['average_january_local_rain_rate_mm_h']>z['average_july_local_rain_rate_mm_h']}
 results['notes']=['These are aggregate associations, not causal proof or physical calibration.',
  'Occupancy and weather are generated by simplified assumptions.',
  'Rain sensor is a synthetic building-local measurement in the packaged dataset.',
  'A weather-driven NASA regeneration must be checked separately.']
 out=Path(out);out.parent.mkdir(parents=True,exist_ok=True);out.write_text(json.dumps(results,indent=2))
 print('CHECKS:',results['checks']);print('VALUES:',z)
 return all(results['checks'].values())

if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--root',default='generated/normal_by_year');p.add_argument('--output',default='generated/llm_reference/quality_report.json');a=p.parse_args()
 if not run(a.root,a.output):raise SystemExit('Some association checks failed; inspect quality_report.json')
