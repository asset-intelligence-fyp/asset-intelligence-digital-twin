"""Optional cached E7 screening replay for paired E8-A inference, labels forbidden."""
from __future__ import annotations
import json
from pathlib import Path
from .e7_validation import utc_stamp
from .schemas import AnomalyAnswer

FORBIDDEN = {"label", "labels", "fault_active", "ground_truth", "ground_truth_label",
             "is_anomaly", "actual_status", "actual_label", "fault_type", "event_id"}


def load_causal_screenings(path: str | Path, *, expected_model: str | None = None):
    result = {}
    with Path(path).open(encoding="utf-8") as infile:
        for i, line in enumerate(infile, 1):
            if not line.strip():
                continue
            entry = json.loads(line)
            if FORBIDDEN.intersection(entry):
                raise ValueError(f"Cached screening {i} contains forbidden label fields")
            if entry.get("task") != "detect" or entry.get("valid") is not True:
                raise ValueError(f"Cached screening {i} is not a valid detect record")
            if expected_model and entry.get("model") != expected_model:
                raise ValueError(f"Cached screening {i} was generated by a different model")
            sensor, origin = entry.get("sensor_id"), entry.get("origin")
            if not isinstance(sensor, str) or not origin:
                raise ValueError(f"Cached screening {i} needs a sensor and origin")
            proposal = entry.get("screening") or entry.get("answer") or {}
            if FORBIDDEN.intersection(proposal):
                raise ValueError(f"Cached screening {i} includes forbidden label fields")
            screen = AnomalyAnswer.model_validate(proposal).model_dump()
            key = (sensor, utc_stamp(origin))
            for ts in screen.get("evidence_timestamps", []):
                if utc_stamp(ts) > key[1]:
                    raise ValueError(f"Cached screening {i} cites future data")
            if key in result:
                raise ValueError(f"Cached screening {i} duplicates {key}")
            result[key] = screen
    if not result:
        raise ValueError("Cached screening file was empty")
    return result
