import {randomBytes,scryptSync,timingSafeEqual} from 'node:crypto';
import {existsSync,lstatSync,readFileSync,writeFileSync,chmodSync} from 'node:fs';
import {resolve} from 'node:path';

// Local-only setup. No plaintext password or verifier is committed to GitHub.
const envPath=resolve(process.cwd(),'.env');
if(existsSync(envPath)&&!lstatSync(envPath).isFile()){
 console.error('Refusing to overwrite .env because it is not a regular file.');
 process.exit(1);
}
const username='admin';
const password=randomBytes(18).toString('base64url');
const salt=randomBytes(16).toString('hex');
const digest=scryptSync(password,Buffer.from(salt,'hex'),64);
const hash=`scrypt:${salt}:${digest.toString('hex')}`;
if(!timingSafeEqual(digest,scryptSync(password,Buffer.from(salt,'hex'),64))){
 throw new Error('Generated password verification failed');
}
const previous=existsSync(envPath)?readFileSync(envPath,'utf8'):'';
// Preserve existing PostgreSQL, simulator, and AI settings; replace prior admin values.
const preserved=previous.split(/\r?\n/)
 .filter(line=>!/^\s*(?:export\s+)?ADMIN_(?:USERNAME|PASSWORD_HASH)\s*=/.test(line))
 .join('\n').trimEnd();
const next=[preserved,'# Local-only administrator; generated by npm run admin:setup.',
 `ADMIN_USERNAME=${username}`,`ADMIN_PASSWORD_HASH=${hash}`,'']
 .filter((part,i)=>i!==0||part!=='').join('\n');
writeFileSync(envPath,next,{encoding:'utf8',mode:0o600});
if(process.platform!=='win32')chmodSync(envPath,0o600);
console.log('\nAdministrator configured in local .env (ignored by Git).');
console.log('Username: '+username);
console.log('Password: '+password);
console.log('\nSave this password somewhere private; it is only displayed once.');
console.log('Restart npm run dev so the server reloads .env.');
console.log('If the password is lost, rerun npm run admin:setup to rotate it.');
console.log('Database preview additionally requires a working PostgreSQL instance.');
if(process.env.ADMIN_USERNAME||process.env.ADMIN_PASSWORD_HASH){
 console.warn('WARNING: Admin settings in your shell may override .env. Unset them before restarting.');
}
